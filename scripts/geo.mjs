// Projects Natural Earth 110m land and the live site's map pins into SVG space.
// node scripts/geo.mjs  →  src/data/geo.ts
import { readFileSync, writeFileSync } from "node:fs";
import { geoEqualEarth, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-110m.json", import.meta.url)));
const countries = feature(topo, topo.objects.countries).features.filter((f) => f.id !== "010"); // drop Antarctica
// The same 60 pins beastphilanthropy.org shows under "Explore Our Work" (title, country, YouTube id, [lon, lat]).
const pins = JSON.parse(readFileSync(new URL("../src/data/site/pins.json", import.meta.url)));

const width = 1000;
const world = { type: "FeatureCollection", features: countries };
const proj = geoEqualEarth().fitWidth(width, world);
const path = geoPath(proj).digits(1);
const [[, y0], [, y1]] = path.bounds(world);
proj.translate([proj.translate()[0], proj.translate()[1] - y0]);
const height = Math.ceil(y1 - y0);

const land = countries.map((f) => path(f)).filter(Boolean).join("");

// Pins sharing a coordinate become one spot with several projects, like the live site's "Project n / total".
const spots = new Map();
for (const p of pins) {
  const key = p.coordinates.join(",");
  if (!spots.has(key)) {
    const [x, y] = proj(p.coordinates);
    spots.set(key, { x: +x.toFixed(1), y: +y.toFixed(1), country: p.country, projects: [] });
  }
  spots.get(key).projects.push({ title: p.title, ytId: p.ytId, country: p.country });
}

// Spots closer than a pin's width can't both be clicked, so they merge into one (the busiest place leads).
const MERGE = 13;
const merged = [];
for (const s of [...spots.values()].sort((a, b) => b.projects.length - a.projects.length)) {
  const near = merged.find((m) => Math.hypot(m.x - s.x, m.y - s.y) < MERGE);
  if (near) near.projects.push(...s.projects);
  else merged.push({ ...s, projects: [...s.projects] });
}
for (const m of merged) {
  const count = {};
  for (const p of m.projects) count[p.country] = (count[p.country] ?? 0) + 1;
  m.country = Object.entries(count).sort((a, b) => b[1] - a[1])[0][0];
}
spots.clear();
merged.forEach((m, i) => spots.set(i, m));

const out = `// Generated by scripts/geo.mjs from Natural Earth 110m (via world-atlas) and src/data/site/pins.json. Do not edit.
export type Project = { title: string; ytId: string; country: string };
export type Spot = { x: number; y: number; country: string; projects: Project[] };
export const MAP = ${JSON.stringify({ width, height })};
export const LAND = ${JSON.stringify(land)};
export const SPOTS: Spot[] = ${JSON.stringify([...spots.values()])};
`;
writeFileSync(new URL("../src/data/geo.ts", import.meta.url), out);
console.log("map", width, height, "land", land.length, "pins", pins.length, "spots", spots.size);
